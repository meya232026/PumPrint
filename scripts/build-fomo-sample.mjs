#!/usr/bin/env node
// Builds public/assets/js/fomo/live-sample.js: one snapshot of Fomo Radar's live view, made by the
// radar itself running on its made-up demo chain (server/fomo/demo.js). The page shows it when the
// site runs without its server. Every wallet, handle and token in it is invented.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createFomo } from '../server/fomo/index.js';

const quiet = { debug() {}, info() {}, warn() {}, error: console.error };
const fomo = createFomo({ dataDir: '.', demo: true, env: {}, log: quiet });
await fomo.ready();
const snapshot = fomo.radar.snapshot();
fomo.close();
const out = fileURLToPath(new URL('../public/assets/js/fomo/live-sample.js', import.meta.url));
writeFileSync(
  out,
  '// A sample of Fomo Radar\'s live view for running without a server. Generated by\n' +
    '// scripts/build-fomo-sample.mjs on a made-up chain: every wallet, handle and token is invented.\n' +
    `export default ${JSON.stringify({ builtAt: snapshot.now, snapshot })};\n`,
);
console.log(`alerts ${snapshot.alerts.length}, held ${snapshot.held.length}, signals ${snapshot.signals.length}, tape ${snapshot.tape.length}`);
console.log('wrote', out);
process.exit(0);
