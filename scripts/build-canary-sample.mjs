#!/usr/bin/env node
// Writes public/assets/js/canary/demo-data.js: one 12-tick cycle of the Canary demo world, swept by the
// site's own adapter (server/canary/index.js in demo mode) on a made-up clock, 4 seconds a sweep. The
// page plays it when there is no server (static hosting, the single-file preview). Everything in it is
// invented: tokens, addresses and the tape.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createCanary } from '../server/canary/index.js';

const STEP = 4000;
const BUILT_AT = Date.UTC(2026, 9, 22, 12, 0, 0);
let t = BUILT_AT - 13 * STEP;
const quiet = { debug() {}, info() {}, warn() {}, error: console.error };
const canary = createCanary({ dataDir: '/nonexistent', demo: true, autostart: false, now: () => t, env: { CANARY_DEMO_SECONDS: String(STEP / 1000) }, log: quiet });
await canary.probe();

const frames = [];
const details = {};
for (let i = 0; i < 13; i++) {
  t += STEP;
  await canary.sweepOnce();
  const s = canary.state(null);
  frames.push({ now: s.now, chain: s.chain, pass: s.pass, stats: s.stats, tokens: s.tokens });
  for (const row of s.tokens) details[row.token.toLowerCase()] = null;
}
// The feed of the last frame holds every alert of the cycle: a frame shows the ones at or before its time.
const last = canary.state(null);
for (const k of Object.keys(details)) {
  const res = { status: 0, body: '' };
  await canary.handle(
    { method: 'GET', headers: {}, socket: {} },
    { writeHead: (st) => (res.status = st), end: (b) => (res.body = b) },
    new URL(`http://x/api/canary/token?token=${k}`),
  );
  const d = JSON.parse(res.body);
  details[k] = { snapshot: d.snapshot, history: d.history };
}
const rules = await (async () => {
  const res = { body: '' };
  await canary.handle({ method: 'GET', headers: {}, socket: {} }, { writeHead() {}, end: (b) => (res.body = b) }, new URL('http://x/api/canary/rules'));
  return JSON.parse(res.body);
})();
canary.close();

const data = { builtAt: BUILT_AT, step: STEP, mode: 'sample', thresholds: last.thresholds, limits: last.limits, rules, alerts: last.alerts, frames, details };
const out = fileURLToPath(new URL('../public/assets/js/canary/demo-data.js', import.meta.url));
const body =
  '// Sample Canary board for running without a server. Generated by scripts/build-canary-sample.mjs.\n' +
  "// Made-up Pons V2 tokens on a scripted tape; every signal computed by Canary's own rules.\n" +
  `export default ${JSON.stringify(data)};\n`;
writeFileSync(out, body);
for (const [i, f] of frames.entries()) console.log(`frame ${String(i).padStart(2)} ${f.tokens.map((x) => `${x.symbol}=${x.status}`).join(' ')}  feed=${last.alerts.filter((a) => a.at <= f.now).length}`);
console.log(`wrote ${out} (${(body.length / 1024).toFixed(1)} KiB, ${frames.length} frames)`);
