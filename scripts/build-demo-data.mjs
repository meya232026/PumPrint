#!/usr/bin/env node
// Builds public/assets/js/kolibri/demo-data.js: sample report cards made by the site's
// Kolibri engine on a simulated market (server/demo-world.cjs). The site shows them when
// it runs without its server (static hosting, previews). Everything in it is made up.

import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createKolEngine } from '../server/kol/engine.js';

const require = createRequire(import.meta.url);
const { createDemoWorld } = require('../server/demo-world.cjs');

const now = Date.now();
const world = createDemoWorld(now);
const quiet = { debug() {}, info() {}, warn() {}, error: console.error };
const engine = createKolEngine({ dataDir: '.', env: {}, log: quiet, fetchImpl: world.fetchImpl, demo: true, now: () => now });

for (const c of world.callers) {
  if (c.platform === 'tg') await engine.collectTelegram(c.handle);
  else await engine.collectX(c.handle);
}
let n;
do n = await engine.priceDue(200);
while (n > 0);

// Keep what the report card shows; drop pricing internals.
const CALL_FIELDS = ['id', 'postId', 'postedAt', 'url', 'snippet', 'symbol', 'mentions', 'status', 'entry', 'entryAt', 'entryMc', 'frame',
  'r1m', 'r5m', 'r1h', 'r24h', 'p1m', 'p5m', 'p1h', 'p24h', 'peak', 'peakAt', 'rPeak', 'rLow', 'supply', 'nextCheckAt'];
const slimCall = (c) => {
  const o = {};
  for (const f of CALL_FIELDS) if (c[f] !== undefined && c[f] !== null) o[f] = c[f];
  o.token = { kind: c.token.kind, symbol: c.token.symbol || null, address: c.token.address || null, chain: c.token.chain || null, symbolHint: c.token.symbolHint || null };
  if (c.market) {
    const m = c.market;
    o.market = { label: m.label, venue: m.venue, url: m.url, chain: m.chain || null, token: m.token || null, symbol: m.symbol, name: m.name || null };
  }
  return o;
};
const cards = {};
for (const c of world.callers) {
  const key = `${c.platform}:${c.handle.toLowerCase()}`;
  const out = engine.card(key);
  cards[key] = { ...out.card, calls: out.card.calls.map(slimCall) };
}
const leaderboard = engine.leaderboard(null, 50);
engine.close();

const out = fileURLToPath(new URL('../public/assets/js/kolibri/demo-data.js', import.meta.url));
writeFileSync(
  out,
  '// Sample Kolibri report cards for running without a server. Generated by scripts/build-demo-data.mjs.\n' +
    '// Made-up callers and tokens, measured by the site\'s Kolibri engine on a simulated market.\n' +
    `export default ${JSON.stringify({ builtAt: now, cards, leaderboard })};\n`,
);
const pc = (v) => (v == null ? '  -' : `${Math.round(v * 100)}%`);
for (const it of leaderboard) {
  const s = it.summary;
  console.log(`${it.key.padEnd(24)} ${s.grade || '-'} score ${s.score} calls ${s.calls} up1h ${pc(s.up1h)} med1h ${pc(s.med1h)} med24 ${pc(s.med24)} 2x ${pc(s.hit2x)}`);
}
console.log('wrote', out);
