#!/usr/bin/env node
// Builds public/assets/js/chameleon/demo-data.js: a frozen sample of the Chameleonscope tab for
// running without a server. Made by the terminal's own engine in its preview mode (no network):
// the engine's 15 Sep 2026 sample tokens plus its invented launch flow. Not live data.

import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { createChameleonEngine } from '../server/chameleon/engine.mjs';
import { makeReader, seedQuantumPreview } from '../server/chameleon/snapshot.mjs';

const require = createRequire(import.meta.url);
const { makeViews } = require('../server/chameleon/views.cjs');
const SRC = fileURLToPath(new URL('../vendor/chameleonscope/src', import.meta.url));
const quiet = { log() {}, info() {}, warn() {}, debug() {}, error: console.error };

const eng = createChameleonEngine({ src: SRC, mode: 'demo', console: quiet, fetch: () => Promise.reject(new Error('offline build')) });
await eng.start();
const { TL } = eng;
seedQuantumPreview(TL);
await new Promise((r) => setTimeout(r, 6500)); // a few ticks of the flow
TL.store.recompute();
const reader = makeReader(TL, makeViews(TL), { rows: 20 });
const snap = reader.snapshot();
// a handful of token pages, so a click in the sample opens something
const details = {};
for (const c of ['solana', 'robinhood']) for (const g of ['new', 'almost', 'graduated']) for (const r of snap.feeds[c][g].rows.slice(0, 6)) details[r.id] = reader.detail(r.id);
for (const card of snap.radar.solana.cards) details[card.id] = reader.detail(card.id);
eng.stop();

const out = fileURLToPath(new URL('../public/assets/js/chameleon/demo-data.js', import.meta.url));
const text =
  '// Chameleonscope sample for running without a server. Generated by scripts/build-chameleon-sample.mjs\n' +
  "// from the terminal's own preview mode (shmidtqq65/chameleonscope, MIT): sample and invented tokens, not live data.\n" +
  `export default ${JSON.stringify({ builtAt: snap.at, snap, details })};\n`;
writeFileSync(out, text);
const f = snap.feeds;
console.log(Object.entries(f).map(([c, g]) => `${c}: ${Object.entries(g).map(([k, v]) => `${k} ${v.rows.length}/${v.total}`).join(' ')}`).join(' | '));
console.log(`radar ${snap.radar.solana.cards.map((x) => x.symbol).join(',')} | calls ${snap.calls.length} | details ${Object.keys(details).length}`);
console.log('wrote', out, `${(text.length / 1024).toFixed(0)} KB`);
process.exit(0);
