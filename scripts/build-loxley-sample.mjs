#!/usr/bin/env node
// Writes public/assets/js/loxley/sample-data.js: one recorded paper session on loxley's mock chain (the demo
// world in server/loxley/demo.js), plus the read answers the page offers (market, a few scans, fees, dev, exit,
// x-ray). The page replays it when there is no server (static hosting, the single-file preview). Every launch,
// wallet and price in it is made up; the market list is the recorded fixture loxley's mock serves.
//   node scripts/build-loxley-sample.mjs [seconds=180]

import { writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadLoxley, makeEnv } from '../server/loxley/safe.js';
import { createPaperDesk } from '../server/loxley/paper.js';
import { createReads } from '../server/loxley/reads.js';
import { makeQuoter } from '../server/loxley/quotes.js';
import { startDemoWorld } from '../server/loxley/demo.js';

const secs = Number(process.argv[2] || 180);
const home = mkdtempSync(join(tmpdir(), 'loxley-sample-'));
const L = loadLoxley({ home });
const W = await startDemoWorld({ L, seed: 2026 });
const env = makeEnv({ ...W.env });
const startedAt = Date.now();
const events = [];
const round = (v) => (typeof v === 'number' && !Number.isInteger(v) ? Number(v.toPrecision(5)) : v);
// links point at the mock's 127.0.0.1 ports: the page builds its own, and only for live data
const DROP = new Set(['links', 'readAt', 'url', 'explorer', 'description', 'logo']);
const slim = (o) => JSON.parse(JSON.stringify(o, (k, v) => (DROP.has(k) ? undefined : k === 'door' && Array.isArray(v) ? v.filter((d) => d.eth === 0.05) : round(v))));
// a follow-up changes the flow, the fill and the score: only those travel, the page merges them into the card
const delta = (c) => ({ token: c.token, flow: c.flow, bonding: c.bonding, score: c.score, deployerRecord: c.deployerRecord, farm: c.farm });
const desk = createPaperDesk({
  L,
  env,
  log: { info() {}, warn() {}, error: console.error },
  flags: { budget: '1000000' },
  traderFor: (chain) => makeQuoter({ L, chain, env }),
  onEvent: (ev) => {
    if (ev.type === 'alert') return;
    const { at, ...rest } = ev;
    if (rest.type === 'follow') rest.card = delta(rest.card);
    events.push(slim({ ...rest, t: at - startedAt }));
  },
});
await desk.start();
await new Promise((r) => setTimeout(r, secs * 1000));
await desk.stop({ closeAll: false });

const R = createReads({ L, ctx: desk.ctx });
const reads = {};
const put = async (key, f) => {
  try {
    reads[key] = slim(await f());
  } catch (e) {
    console.warn(key, e.message);
  }
};
await put('market', () => R.market({ top: 20 }));
const cards = desk.snapshot().cards;
const pickTok = (f) => (cards.find(f) || {}).token;
for (const tok of [pickTok((c) => c.score && c.score.verdict === 'FIRE'), pickTok((c) => c.bonding && c.bonding.graduated), pickTok((c) => c.score && c.score.verdict === 'SKIP'), W.M.TOKEN].filter(Boolean)) {
  await put(`scan:${tok.toLowerCase()}`, () => R.scan(tok));
}
await put(`exit:${W.M.TOKEN.toLowerCase()}`, () => R.exit(W.M.TOKEN));
await put(`fees:${W.M.TOKEN.toLowerCase()}`, () => R.fees(W.M.TOKEN));
const snap = desk.snapshot();
const out = {
  builtAt: Date.now(),
  startedAt,
  duration: secs * 1000,
  note: "made-up launches on loxley's mock chain: nothing here is real",
  hello: { mode: 'sample', pace: 'demo', paper: true, version: snap.version, rules: snap.rules, rulesText: desk.rulesText },
  events,
  reads,
};
const file = fileURLToPath(new URL('../public/assets/js/loxley/sample-data.js', import.meta.url));
const body =
  '// Recorded Loxley paper session on the mock chain, for running without a server. Generated by scripts/build-loxley-sample.mjs.\n' +
  '// Made-up launches, wallets and prices.\n' +
  `export default ${JSON.stringify(out)};\n`;
writeFileSync(file, body);
const by = {};
for (const e of events) by[e.type] = (by[e.type] || 0) + 1;
console.log('wrote', file, `${(body.length / 1024).toFixed(0)} KB`, JSON.stringify(by), 'reads', Object.keys(reads).join(' '), 'totals', JSON.stringify(snap.totals));
await W.close();
rmSync(home, { recursive: true, force: true });
process.exit(0);
