#!/usr/bin/env node
// Compiles Canary (vendor/canary, TypeScript) into plain JavaScript for the site. Needs esbuild, which
// the site itself does not: the outputs are committed, so this only runs after updating vendor/canary.
//
//   node scripts/build-canary.mjs           server/canary/engine.mjs + public/assets/js/canary/rules.js
//   node scripts/build-canary.mjs --test    also runs Canary's own test suite against the same build
//
// esbuild is looked up in node_modules, then in ESBUILD_PATH (a folder that has esbuild in it).
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { mkdtempSync, readdirSync, rmSync, statSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';

const require = createRequire(import.meta.url);
const ROOT = fileURLToPath(new URL('..', import.meta.url));
const CANARY = join(ROOT, 'vendor/canary');
const SHIM = join(ROOT, 'server/canary/viem-shim.mjs');

function loadEsbuild() {
  const tries = ['esbuild', process.env.ESBUILD_PATH && join(process.env.ESBUILD_PATH, 'esbuild')];
  for (const t of tries.filter(Boolean)) {
    try {
      return require(t);
    } catch {
      /* next */
    }
  }
  console.error('esbuild not found. Install it once with `npm i --no-save esbuild` or set ESBUILD_PATH.');
  process.exit(1);
}
const esbuild = loadEsbuild();

// Canary's `import ... from "viem"` stays an import, of the read-only shim next to the engine.
const viemToShim = (shimPath) => ({
  name: 'viem-to-shim',
  setup(b) {
    b.onResolve({ filter: /^viem$/ }, () => ({ path: shimPath, external: true }));
  },
});
const common = { bundle: true, platform: 'node', format: 'esm', target: 'node22', legalComments: 'inline', logLevel: 'warning' };
const header = (what) => `// ${what}\n// Generated by scripts/build-canary.mjs from vendor/canary (Canary v0.4, MIT, github.com/Gipppp121/canary). Do not edit.\n`;

// 1. the engine the site runs
const engineOut = join(ROOT, 'server/canary/engine.mjs');
await esbuild.build({
  ...common,
  entryPoints: [join(ROOT, 'server/canary/entry.ts')],
  outfile: engineOut,
  plugins: [viemToShim('./viem-shim.mjs')],
  banner: { js: header('Canary\'s reader, rules, store and alert sinks for the site.') },
});

// 2. Canary's rules for the browser: the page runs them on the scans a visitor watches in their tab.
// signals.ts imports nothing, so a one-to-one transpile is the whole module.
const rulesOut = join(ROOT, 'public/assets/js/canary/rules.js');
await esbuild.build({
  entryPoints: [join(CANARY, 'src/watch/signals.ts')],
  outfile: rulesOut,
  bundle: false,
  format: 'esm',
  platform: 'neutral',
  target: 'es2020',
  logLevel: 'warning',
  banner: { js: header('Canary\'s ten deterministic rules (src/watch/signals.ts), for the browser.') },
});
for (const f of [engineOut, rulesOut]) console.log(`${f.replace(ROOT, '')}  ${(statSync(f).size / 1024).toFixed(1)} KiB`);

// The engine must not carry any code of its own that writes to a chain.
const engine = readFileSync(engineOut, 'utf8');
const banned = /sendRawTransaction|eth_sendTransaction|signTransaction|signMessage|createWalletClient|privateKeyToAccount|mnemonicToAccount/;
if (banned.test(engine)) {
  console.error('engine.mjs contains a signing or write primitive; refusing to keep it');
  rmSync(engineOut);
  process.exit(1);
}

// 3. optional: Canary's own tests, compiled the same way, run with node --test
if (process.argv.includes('--test')) {
  const dir = mkdtempSync(join(tmpdir(), 'canary-tests-'));
  const tests = readdirSync(join(CANARY, 'test')).filter((f) => f.endsWith('.test.ts'));
  await esbuild.build({
    ...common,
    entryPoints: tests.map((f) => join(CANARY, 'test', f)),
    outdir: dir,
    outExtension: { '.js': '.mjs' },
    plugins: [viemToShim(SHIM)],
  });
  const files = readdirSync(dir).map((f) => join(dir, f));
  const r = spawnSync(process.execPath, ['--test', ...files], { stdio: 'inherit' });
  rmSync(dir, { recursive: true, force: true });
  process.exit(r.status ?? 1);
}
